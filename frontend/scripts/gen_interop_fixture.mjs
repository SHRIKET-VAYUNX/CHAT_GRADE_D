/**
 * One-off generator for the frontend↔backend RSA-1024 interop fixture.
 *
 * Produces an RSA-1024 keypair with `node-forge` (the frontend's crypto lib),
 * signs a fixed message with PKCS#1 v1.5 + MD5, and RSA-encrypts (PKCS#1 v1.5)
 * a fixed 16-byte symmetric key under the public key — exactly the Grade D
 * identity-key + key-transport primitives the live frontend uses. The output
 * JSON is consumed by `backend/tests/crypto/test_frontend_interop.py`, which
 * feeds these forge-produced artifacts into the backend's Python `cryptography`
 * providers to prove byte-for-byte interop (forge DER / signatures / RSA
 * ciphertext are accepted by the backend).
 *
 * Run: `node frontend/scripts/gen_interop_fixture.mjs` (from the repo root, with
 * `frontend/node_modules` installed). The RSA keygen is not deterministic, so
 * this is run ONCE and the resulting fixture is committed.
 */
import forge from "node-forge";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "..", "..", "backend", "tests", "fixtures");
const outPath = resolve(outDir, "forge_rsa1024_interop.json");

const MESSAGE = new TextEncoder().encode("vayunx grade-d frontend/backend interop");
const SYMMETRIC_KEY = new Uint8Array([0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42]);

const keyPair = forge.pki.rsa.generateKeyPair({ bits: 1024, e: 0x10001 });

// DER SubjectPublicKeyInfo (public) + DER PKCS#8 unencrypted (private).
const spkiDer = forge.asn1.toDer(forge.pki.publicKeyToAsn1(keyPair.publicKey)).getBytes();
const pkcs8Der = forge.asn1
  .toDer(forge.pki.wrapRsaPrivateKey(forge.pki.privateKeyToAsn1(keyPair.privateKey)))
  .getBytes();

// PKCS#1 v1.5 signature over MD5 of the message (forge binary strings).
const md = forge.md.md5.create().update(String.fromCharCode(...MESSAGE));
const signature = keyPair.privateKey.sign(md);

// PKCS#1 v1.5 key transport: RSA-encrypt the symmetric key under the public key.
const encapsulation = keyPair.publicKey.encrypt(
  String.fromCharCode(...SYMMETRIC_KEY),
  "RSAES-PKCS1-V1_5",
);

function b64(binaryStr) {
  return Buffer.from(binaryStr, "binary").toString("base64");
}

const fixture = {
  _note: "Generated by frontend/scripts/gen_interop_fixture.mjs. forge (node) artifacts consumed by backend/tests/crypto/test_frontend_interop.py.",
  spki_b64: b64(spkiDer),
  pkcs8_b64: b64(pkcs8Der),
  message_b64: Buffer.from(MESSAGE).toString("base64"),
  signature_b64: b64(signature),
  encapsulation_b64: b64(encapsulation),
  symmetric_key_b64: Buffer.from(SYMMETRIC_KEY).toString("base64"),
};

mkdirSync(outDir, { recursive: true });
writeFileSync(outPath, JSON.stringify(fixture, null, 2) + "\n");
console.log(`Wrote ${outPath}`);